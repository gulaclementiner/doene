//! Translations (i18n) — port of Gör't `src/i18n.js` (docs/plan.md §8).
//!
//! Strings live in plain-text data files, one per language (`locales/<tag>.txt`,
//! compiled into the binary by `build.rs`). Each line is `key=value`: flat dotted
//! keys, value after the first `=`. Adding a language is dropping in one new
//! data file — no lookup-code change. Lookup is locale → English → the key
//! itself, so a missing string is visible instead of blank.

use std::collections::{BTreeMap, HashMap};
use std::sync::{Mutex, OnceLock};

/// Locale used when none is chosen or the chosen one has no string.
pub const DEFAULT_LOCALE: &str = "en";

// The locale tables compiled in from `locales/*.txt` (one file per language;
// generated by build.rs as a const item).
include!(concat!(env!("OUT_DIR"), "/locale_files.inc"));

/// A parsed locale table: flat dotted key → string.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct LocaleTable(BTreeMap<String, String>);

/// Returned when a data file line is not a valid `key=value` entry.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TableError {
    /// A non-blank, non-comment line has no `=` separator.
    MissingSeparator,
    /// The key is empty or not flat dotted word segments (`nav.myDay`).
    BadKey,
    /// The same key appears twice in one file.
    DuplicateKey,
}

impl std::fmt::Display for TableError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let msg = match self {
            Self::MissingSeparator => "line has no '=' separator",
            Self::BadKey => "key is not flat dotted word segments",
            Self::DuplicateKey => "duplicate key in locale file",
        };
        f.write_str(msg)
    }
}

impl std::error::Error for TableError {}

fn is_word_char(c: char) -> bool {
    c.is_ascii_alphanumeric() || c == '_'
}

/// A flat dotted table key: segments of word chars (plus `-`) joined by dots
/// (`nav.myDay`, `myday.group.starred-due`).
fn is_key_shape(s: &str) -> bool {
    let ok = |c: char| is_word_char(c) || c == '-';
    let mut segments = s.split('.');
    match segments.next() {
        Some(first) if !first.is_empty() && first.chars().all(ok) => {}
        _ => return false,
    }
    segments.all(|seg| !seg.is_empty() && seg.chars().all(ok))
}

impl LocaleTable {
    /// Parse a plain-text locale file: one `key=value` per line, split on the
    /// first `=`; blank lines and `#` comments are ignored. Duplicate keys are
    /// an error so a bad data file fails the build instead of hiding strings.
    pub fn parse(text: &str) -> Result<Self, TableError> {
        let mut entries = BTreeMap::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (key, value) = line.split_once('=').ok_or(TableError::MissingSeparator)?;
            if !is_key_shape(key) {
                return Err(TableError::BadKey);
            }
            if entries.insert(key.to_owned(), value.to_owned()).is_some() {
                return Err(TableError::DuplicateKey);
            }
        }
        Ok(Self(entries))
    }

    /// The string for `key`, if this table defines it.
    pub fn get(&self, key: &str) -> Option<&str> {
        self.0.get(key).map(|s| s.as_str())
    }

    /// All keys in sorted order.
    pub fn keys(&self) -> Vec<&str> {
        self.0.keys().map(|k| k.as_str()).collect()
    }
}

/// base tag → table, seeded from the compiled-in data files and extended by
/// [`load_locale`].
type Registry = HashMap<String, BTreeMap<String, String>>;

fn registry() -> &'static Mutex<Registry> {
    static REGISTRY: OnceLock<Mutex<Registry>> = OnceLock::new();
    REGISTRY.get_or_init(|| {
        let mut reg = Registry::new();
        for (tag, text) in LOCALE_FILES {
            let table = LocaleTable::parse(text).expect("compiled-in locale file is valid");
            reg.insert((*tag).to_owned(), table.0);
        }
        Mutex::new(reg)
    })
}

/// The base of a locale tag: lower-cased, region/script dropped, so `sv-SE`
/// and `SV_se` both address `sv`. No locale gives the empty string.
pub fn locale_base(locale: Option<&str>) -> String {
    match locale {
        Some(tag) => tag
            .trim()
            .to_lowercase()
            .split(['-', '_'])
            .next()
            .unwrap_or("")
            .to_owned(),
        None => String::new(),
    }
}

/// The locales shipped in the binary, sorted: one per compiled-in data file.
pub fn locales() -> Vec<&'static str> {
    LOCALE_FILES.iter().map(|(tag, _)| *tag).collect()
}

/// The string for `key` in `locale`, else in English, else `None`.
fn lookup(key: &str, locale: Option<&str>) -> Option<String> {
    let reg = registry().lock().expect("i18n registry poisoned");
    let tag = locale_base(locale);
    if let Some(table) = reg.get(&tag)
        && let Some(value) = table.get(key)
    {
        return Some(value.clone());
    }
    if tag == DEFAULT_LOCALE {
        return None;
    }
    reg.get(DEFAULT_LOCALE)?.get(key).cloned()
}

/// Fills `{placeholder}`s from `params`. A placeholder with no var (or a null
/// var) is left as written, so gaps stay visible.
fn interpolate(template: &str, params: &HashMap<String, Option<String>>) -> String {
    let chars: Vec<char> = template.chars().collect();
    let mut out = String::with_capacity(template.len());
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '{' {
            let mut j = i + 1;
            let mut name = String::new();
            while j < chars.len() && is_word_char(chars[j]) {
                name.push(chars[j]);
                j += 1;
            }
            if !name.is_empty() && j < chars.len() && chars[j] == '}' {
                out.push_str(&match params.get(name.as_str()) {
                    Some(Some(value)) => value.clone(),
                    _ => format!("{{{name}}}"), // no var / null → left visible
                });
                i = j + 1;
            } else {
                out.push('{'); // not a well-formed placeholder: keep as written
                i += 1;
            }
        } else {
            out.push(chars[i]);
            i += 1;
        }
    }
    out
}

/// A locale-key shape: dotted, word segments (`what.task`). Only such values
/// are ever resolved as keys.
fn is_dotted_key_shape(s: &str) -> bool {
    let mut segments = s.split('.');
    match segments.next() {
        Some(first) if !first.is_empty() && first.chars().all(is_word_char) => {}
        _ => return false,
    }
    // at least one dot
    segments
        .next()
        .is_some_and(|seg| !seg.is_empty() && seg.chars().all(is_word_char))
        && segments.all(|seg| !seg.is_empty() && seg.chars().all(is_word_char))
}

/// A param value that is itself a known locale key (e.g. `what.task`) becomes
/// its localized string.
fn resolve_param(value: &str, locale: Option<&str>) -> String {
    if !is_dotted_key_shape(value) {
        return value.to_owned();
    }
    lookup(value, locale).unwrap_or_else(|| value.to_owned())
}

/// Merges `strings` into the table for `locale` (base tag) and returns the
/// merged table. Used by tests; production locales come from the compiled-in
/// data files.
pub fn load_locale(
    locale: &str,
    strings: impl IntoIterator<Item = (String, String)>,
) -> BTreeMap<String, String> {
    let mut reg = registry().lock().expect("i18n registry poisoned");
    let table = reg.entry(locale_base(Some(locale))).or_default();
    for (key, value) in strings {
        table.insert(key, value);
    }
    table.clone()
}

/// Translates `key`, interpolating `{placeholder}`s from `params` (a `None`
/// value leaves the placeholder visible). Falls back to English, then to the
/// key itself. A param value that is a known locale key resolves to its
/// localized value.
pub fn tr(key: &str, params: &HashMap<String, Option<String>>, locale: Option<&str>) -> String {
    let Some(template) = lookup(key, locale) else {
        return key.to_owned();
    };
    let resolved: HashMap<String, Option<String>> = params
        .iter()
        .map(|(name, value)| match value {
            Some(v) => (name.clone(), Some(resolve_param(v, locale))),
            None => (name.clone(), None),
        })
        .collect();
    interpolate(&template, &resolved)
}

/// JS `String(n)` for the values we render: integral numbers without a decimal
/// point (`1` not `1.0`), shortest round-trip digits otherwise.
pub fn js_number(n: f64) -> String {
    if n.is_finite() && n.fract() == 0.0 && n.abs() <= 9_007_199_254_740_991.0 {
        (n as i64).to_string()
    } else {
        format!("{n}")
    }
}

/// The CLDR plural category for `n` in the locale's base language.
/// en/sv: `one` only for exactly 1. pl: `one`=1, `few`=2..4 (not 12..14 per
/// hundred), `many`=remaining integers, `other`=fractional. Any other locale
/// uses the English rules (only en/sv ship; see docs/divergences.md).
pub fn plural_category(locale: Option<&str>, n: f64) -> &'static str {
    match locale_base(locale).as_str() {
        "pl" => {
            if n.is_finite() && n.fract() == 0.0 && n.abs() <= 9_007_199_254_740_991.0 {
                let i = (n as i64).unsigned_abs();
                match i % 10 {
                    1 if i == 1 => "one",
                    2..=4 if !(12u64..=14).contains(&(i % 100)) => "few",
                    _ => "many",
                }
            } else {
                "other"
            }
        }
        _ => {
            if n == 1.0 {
                "one"
            } else {
                "other"
            }
        }
    }
}

/// Picks `key.<category>` for the count, falling back to `key.other` (and then
/// English) before giving up with a stable `key.<category>` string. The chosen
/// form is interpolated with `{n}`.
pub fn plural(key: &str, n: f64, locale: Option<&str>) -> String {
    let category = plural_category(locale, n);
    let primary = format!("{key}.{category}");
    let other = format!("{key}.other");
    let candidates: Vec<String> = if category == "other" {
        vec![primary]
    } else {
        vec![primary, other]
    };
    let n_param: HashMap<String, Option<String>> =
        [("n".to_owned(), Some(js_number(n)))].into_iter().collect();
    for candidate in &candidates {
        if let Some(template) = lookup(candidate, locale) {
            return interpolate(&template, &n_param);
        }
    }
    format!("{key}.{category}")
}

/// JS `parseFloat` for the tiny `q=` values we parse: reads a leading numeric
/// prefix, anything else is 0 (JS NaN → q 0).
fn js_parse_float(s: &str) -> f64 {
    let s = s.trim();
    for end in (1..=s.len()).rev() {
        if let Ok(v) = s[..end].parse::<f64>() {
            return v;
        }
    }
    0.0
}

/// The `q` weight of one Accept-Language entry (default 1).
fn q_value(entry: &str) -> f64 {
    for param in entry.split(';') {
        let param = param.trim();
        if param.len() > 2 && param.to_lowercase().starts_with("q=") {
            return js_parse_float(&param[2..]);
        }
    }
    1.0
}

/// The best supported language for an Accept-Language header: highest `q`
/// first, exact tag then base tag; no usable entry means the default locale.
pub fn detect_language(accept_language: Option<&str>) -> &'static str {
    let Some(header) = accept_language else {
        return DEFAULT_LOCALE;
    };
    let mut entries: Vec<(f64, String)> = header
        .split(',')
        .filter_map(|part| {
            let part = part.trim();
            if part.is_empty() {
                return None;
            }
            let (tag, q) = match part.split_once(';') {
                Some((tag, rest)) => (tag.trim(), q_value(rest)),
                None => (part, 1.0),
            };
            Some((q, tag.to_lowercase()))
        })
        .collect();
    entries.sort_by(|a, b| b.0.partial_cmp(&a.0).unwrap_or(std::cmp::Ordering::Equal));
    for (_, tag) in &entries {
        if let Some((static_tag, _)) = LOCALE_FILES.iter().find(|(t, _)| *t == tag.as_str()) {
            return static_tag;
        }
        let base = locale_base(Some(tag));
        if let Some((static_tag, _)) = LOCALE_FILES.iter().find(|(t, _)| *t == base) {
            return static_tag;
        }
    }
    DEFAULT_LOCALE
}

/// Monday (1) for Swedish, Sunday (0) otherwise — the week-start setting.
pub fn week_start(locale: Option<&str>) -> u8 {
    if locale_base(locale) == "sv" { 1 } else { 0 }
}

/// The regional tag used for date/number formatting: en → en-GB, sv → sv-SE,
/// other bases pass through, no locale → the default.
pub fn display_tag(locale: Option<&str>) -> String {
    let base = locale_base(locale);
    match base.as_str() {
        "en" => "en-GB".to_owned(),
        "sv" => "sv-SE".to_owned(),
        "" => DEFAULT_LOCALE.to_owned(),
        other => other.to_owned(),
    }
}

/// Groups digits per locale: en `1,234` / `1.5`, sv `1\u{00A0}234` / `1,5`
/// (pinned CLDR styles; unknown locales get plain digits — see
/// docs/divergences.md).
pub fn format_number(n: f64, locale: Option<&str>) -> String {
    let tag = display_tag(locale);
    let (group, decimal) = match locale_base(Some(&tag)).as_str() {
        "en" => (',', '.'),
        "sv" => ('\u{00A0}', ','),
        _ => return js_number(n),
    };
    let s = js_number(n);
    let (sign, digits) = match s.strip_prefix('-') {
        Some(d) => ("-", d),
        None => ("", s.as_str()),
    };
    let (int_part, frac) = match digits.split_once('.') {
        Some((i, f)) => (i, Some(f)),
        None => (digits, None),
    };
    let chars: Vec<char> = int_part.chars().collect();
    let mut grouped = String::new();
    for (idx, c) in chars.iter().enumerate() {
        if idx > 0 && (chars.len() - idx).is_multiple_of(3) {
            grouped.push(group);
        }
        grouped.push(*c);
    }
    let mut out = String::from(sign);
    out.push_str(&grouped);
    if let Some(frac) = frac {
        out.push(decimal);
        out.push_str(frac);
    }
    out
}

/// A parsed error body (Gör't `errorMessage` input shape): the server's
/// English `error` sentence, an optional locale-key `code`, and its params.
pub struct ErrorBody<'a> {
    pub code: Option<&'a str>,
    pub params: &'a HashMap<String, String>,
    pub error: Option<&'a str>,
}

/// The sentence a failed API call should show. A body carrying a known `code`
/// renders that code's sentence in the user's locale (params interpolated);
/// an unknown code or an uncoded body falls back to the server's English
/// `error` string; no body at all yields the plain translated generic.
pub fn error_message(body: Option<&ErrorBody<'_>>, locale: Option<&str>) -> String {
    if let Some(b) = body {
        if let Some(code) = b.code.filter(|c| !c.is_empty())
            && lookup(code, locale).is_some()
        {
            let p: HashMap<String, Option<String>> = b
                .params
                .iter()
                .map(|(k, v)| (k.clone(), Some(v.clone())))
                .collect();
            return tr(code, &p, locale);
        }
        if let Some(error) = b.error.filter(|e| !e.is_empty()) {
            return error.to_owned();
        }
    }
    tr("error.notFoundGeneric", &HashMap::new(), locale)
}

