    #[test]
    fn plural_category_rules_for_shipped_and_fixture_locales() {
        // en/sv: one only for exactly 1 (CLDR)
        assert_eq!(plural_category(Some("en"), 1.0), "one");
        assert_eq!(plural_category(Some("sv"), 1.0), "one");
        assert_eq!(plural_category(Some("en"), 0.0), "other");
        assert_eq!(plural_category(Some("en"), 2.0), "other");
        assert_eq!(plural_category(Some("sv"), 1.5), "other");
        // pl (CLDR): one=1; few=2..4 except 12..14 per hundred; many=rest of integers
        assert_eq!(plural_category(Some("pl"), 1.0), "one");
        for n in [2.0, 3.0, 4.0, 22.0, 23.0, 24.0] {
            assert_eq!(plural_category(Some("pl"), n), "few", "pl {n}");
        }
        for n in [
            0.0, 5.0, 10.0, 11.0, 12.0, 13.0, 14.0, 15.0, 21.0, 25.0, 30.0,
        ] {
            assert_eq!(plural_category(Some("pl"), n), "many", "pl {n}");
        }
        assert_eq!(plural_category(Some("pl"), 1.5), "other");
        // unknown locale → English rules
        assert_eq!(plural_category(Some("zz"), 1.0), "one");
        assert_eq!(plural_category(None, 2.0), "other");
    }

