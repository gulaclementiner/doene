    #[test]
    fn error_message_an_unparseable_body_never_leaks_a_raw_method_path_status_string() {
        let message = error_message(None, Some("sv"));
        assert!(!has_three_consecutive_digits(&message), "{message}");
        for verb in ["GET", "PATCH", "POST", "PUT", "DELETE"] {
            assert!(!contains_word(&message, verb), "{verb} leaked: {message}");
        }
    }

    fn has_three_consecutive_digits(s: &str) -> bool {
        s.as_bytes()
            .windows(3)
            .any(|w| w.iter().all(|b| b.is_ascii_digit()))
    }

    fn contains_word(s: &str, word: &str) -> bool {
        let upper = s.to_uppercase();
        upper
            .split(|c: char| !c.is_alphanumeric())
            .any(|w| w == word)
    }

