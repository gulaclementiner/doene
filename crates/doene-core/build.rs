//! Compiles the locale data files into the binary (docs/plan.md §8).
//!
//! Every `locales/*.txt` file becomes one entry of a const table; the tag is
//! the file stem. Adding a language is dropping in one new data file — no
//! lookup-code change.

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let locale_dir = Path::new("locales");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is set by cargo");

    let mut files: Vec<(String, String)> = fs::read_dir(locale_dir)
        .expect("locales/ directory exists")
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "txt"))
        .map(|path| {
            let tag = path
                .file_stem()
                .expect("locale file has a stem")
                .to_string_lossy()
                .into_owned();
            (
                tag,
                fs::read_to_string(&path).expect("locale file is readable UTF-8"),
            )
        })
        .collect();
    files.sort_by(|a, b| a.0.cmp(&b.0));

    let mut inc = String::from("// Generated by build.rs from locales/*.txt — do not edit.\n");
    inc.push_str("const LOCALE_FILES: &[(&str, &str)] = &[\n");
    for (tag, text) in &files {
        inc.push_str(&format!("    ({tag:?}, {text:?}),\n"));
    }
    inc.push_str("];\n");

    fs::write(Path::new(&out_dir).join("locale_files.inc"), inc).expect("writes OUT_DIR");
    println!("cargo:rerun-if-chang=locales");
}
